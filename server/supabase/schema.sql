-- CBT 咨询师练习小程序：Supabase 初始化表结构
-- 在 Supabase Dashboard -> SQL Editor -> New query 中整段执行。

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  student_name varchar(64) not null,
  student_id varchar(128) not null,
  type varchar(32) not null,
  title varchar(255) not null,
  "group" text,
  sub text,
  content jsonb not null,
  status varchar(32) not null default 'pending',
  score integer,
  comment varchar(2000),
  graded_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists submissions_student_id_idx
  on public.submissions (student_id);

create index if not exists submissions_status_created_at_idx
  on public.submissions (status, created_at desc);

create table if not exists public.drafts (
  id bigint generated by default as identity primary key,
  student_id varchar(128) not null,
  key varchar(200) not null,
  data text not null,
  updated_at timestamptz not null default now(),
  unique (student_id, key)
);

create index if not exists drafts_student_id_updated_at_idx
  on public.drafts (student_id, updated_at desc);
